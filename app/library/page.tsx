import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { Metadata } from "next";
import { ComponentsGallery } from "@/components/components/gallery";
import { catalog } from "@/lib/components/catalog";

export const metadata: Metadata = {
  title: "Samuel’s UI Library",
  description:
    "Components, assets, and interaction notes by Samuel. Live examples and source you can take with you.",
  alternates: { canonical: "https://ui.samhc.us" },
  openGraph: { title: "Samuel’s UI Library", description: "Components, assets, and interaction notes by Samuel.", url: "https://ui.samhc.us", siteName: "Samuel’s UI Library" },
};

/**
 * Read a component's source from its built registry item. Single source of
 * truth: public/r/*.json (generated by scripts/build-registry.mjs). public/ is
 * always present in `output: standalone`, and this runs at build time.
 */
function readFiles(slug: string): { path: string; content: string }[] {
  const json = JSON.parse(readFileSync(join(process.cwd(), "public", "r", `${slug}.json`), "utf8"));
  return json.files.map((file: { path: string; target?: string; content: string }) => ({ path: file.target ?? file.path, content: file.content }));
}

export default function ComponentsPage() {
  const items = catalog.map((c) => { const files = readFiles(c.slug); return { ...c, code: files[0]?.content ?? "", files }; });

  return (
    // mh-base shields the whole library from the site-wide colour/text/font
    // toggles: component previews always render in the true theme palette + Inter.
    // data-fullbleed breaks this page out of the fixed 1152px canvas (globals.css)
    // so the library renders as a true full-width desktop site.
    <main className="mh-base" data-fullbleed>
      <ComponentsGallery items={items} />
    </main>
  );
}
